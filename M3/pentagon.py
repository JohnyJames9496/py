import turtle
import time

t = turtle.Turtle()

t.color("red", "blue")  # outline red, fill blue

t.begin_fill()

t.forward(100)
t.right(72)
time.sleep(2)

t.forward(100)
t.right(72)
time.sleep(2)

t.forward(100)
t.right(72)
time.sleep(2)

t.forward(100)
t.right(72)
time.sleep(2)

t.forward(100)
t.right(72)
time.sleep(2)

t.end_fill()

turtle.done()